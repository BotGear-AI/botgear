def lookup_vendor(mac: str) -> Optional[str]:
    """Best-effort vendor name for a MAC address. None if unknown."""
    if not mac:
        return None
    normalized = mac.upper().replace("-", ":")
    parts = normalized.split(":")
    if len(parts) < 3:
        return None
    prefix = ":".join(parts[:3])
    return _OUI_PREFIXES.get(prefix)
